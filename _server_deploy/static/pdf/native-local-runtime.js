        c: c,
        x0: x0, y0: y0, x1: x1, y1: y1,
        w: Number.isInteger(Number(item.w)) ? Number(item.w) : -1,
        bk: Number.isInteger(Number(item.bk)) ? Number(item.bk) : -1,
        sp: !!item.sp,
