  function listCRUD(kind, responseKey, input, init, url, method, idPrefix) {
    return readState(kind, []).then(function (items) {
      if (method === 'GET') {
        var response = { ok: true }; response[responseKey] = items; return jsonResponse(response);
      }
      if (method === 'DELETE') {
        return bodyJSON(input, init).catch(function () { return {}; }).then(function (body) {
          var id = queryId(url) || String(body.id || '');
          return writeState(kind, items.filter(function (item) {
            return String(item && item.id || '') !== id;
          })).then(function () { return jsonResponse({ ok: true }); });
        });
      }
      return bodyJSON(input, init).then(function (body) {
        var id = String(body.id || '');
        var found = id && items.find(function (item) { return item.id === id; });
        if (method === 'PATCH' && !found) return jsonResponse({ ok: false, error: 'not_found' }, 404);
        if (method === 'PATCH') {
          Object.keys(body).forEach(function (key) {
            if (key !== 'file' && key !== 'id') found[key] = clone(body[key]);
          });
        } else {
          var created = clone(body);
          delete created.file;
          created.id = id || idPrefix + randomHex(6);
          created.time = Number(created.time) || nowSeconds();
          items = items.filter(function (item) { return item.id !== created.id; });
          items.push(created);
          found = created;
        }
        return writeState(kind, items).then(function () {
          var response = { ok: true, id: found.id };
          response[responseKey === 'pages' ? 'page' : responseKey.slice(0, -1)] = found;
          if (responseKey === 'highlights') response.highlight = found;
          if (responseKey === 'notes') response.note = found;
          return jsonResponse(response);
        });
      });
    });
  }

