test("every learning Anki projection separates the scrollable face from the fixed rating footer", () => {
  const start = FLASHCARD.indexOf("function cardHtml(st, c, i)");
  const end = FLASHCARD.indexOf("function bindSlide", start);
  const renderer = FLASHCARD.slice(start, end);

  assert.match(
    renderer,
    /<div class="fc-card fc-review-card">[\s\S]*?<div class="fc-review-scroll">/,
  );
  assert.match(
    renderer,
    /var footerControls = c\._showBack[\s\S]*?\? answerControls[\s\S]*?fc-reveal[\s\S]*?data-fc="reveal"[\s\S]*?显示答案/,
  );
  assert.match(
    renderer,
    /<div class="fc-review-footer">['"]?\s*\+\s*footerControls/,
    "the card footer must exist before and after answer reveal",
  );
  assert.ok(
    renderer.indexOf("fc-review-scroll") <
      renderer.indexOf("fc-review-footer"),
    "rating controls must be a sibling after the scrollable face",
  );
  assert.match(
    FLASHCARD,
    /\.fc-review-scroll\{[^}]*overflow-y:auto[^}]*\}/,
  );
  assert.match(
    FLASHCARD,
    /\.fc-review-footer\{[^}]*flex:0 0 auto[^}]*\}/,
  );
  assert.match(
    FLASHCARD,
    /\.fc-reveal\{[^}]*width:100%[^}]*\}/,
    "the pre-answer action must occupy the fixed footer",
  );
  assert.doesNotMatch(
    FLASHCARD,
    /\.fc-review-footer\{[^}]*overflow-y:auto/,
  );
  assert.doesNotMatch(
    renderer,
    /return '<div class="fc-card">' \+ body/,
    "ordinary learning cards must not fall back to the old scrolling action layout",
  );
});

test("controlled reveal supports answer-only replacement without changing other modes", () => {
  const start = FLASHCARD.indexOf("function cardHtml(st, c, i)");
  const end = FLASHCARD.indexOf("function bindSlide", start);
  const renderer = FLASHCARD.slice(start, end);

  assert.match(
    renderer,
    /c\._revealMode === 'replace'[\s\S]*?fc-answer-only/,
  );
  assert.match(
    renderer,
    /fc-answer-only[^+]*['"]\s*\+\s*back/,
  );
  assert.ok(
    renderer.includes(
      `: '<div class="fc-face">' + front + '<div class="fc-back">' + back + '</div></div>'`,
    ),
    "append remains the default controlled-review reveal",
  );
  // 预览态必须在受控复习分支之前**自己 return**，不与复习/草稿态共用渲染。
  // （原断言靠"preview 之后还能看到 <div class="fc-lbl">正面"来间接确认这一点，
  //   而正面/背面这两个标题已按用户要求从预览里去掉、只留在草稿的可编辑态，
  //   且草稿分支现在排在 preview 之前 —— 那条正则从此只是在验行文顺序。）
  const preview = renderer.slice(renderer.indexOf("if (c._st === 'preview')"));
  assert.ok(preview.length > 0, "预览态必须有自己的分支");
  const previewBody = preview.slice(0, preview.indexOf("}"));
  assert.match(previewBody, /return '<div class="fc-card">'/);
  assert.doesNotMatch(previewBody, /fc-lbl|fc-reveal|fc-eases|data-fc="reveal"/);
});

test("unsaved drafts render ruby through the same safe face projection while keeping source editing", () => {
  const helperStart = FLASHCARD.indexOf("function draftFieldHtml(st, card, label, field, side)");
  const helperEnd = FLASHCARD.indexOf("var _EASE", helperStart);
  assert.ok(helperStart >= 0 && helperEnd > helperStart, "draft rich preview helper must exist");
  const helper = FLASHCARD.slice(helperStart, helperEnd);
  assert.match(helper, /fc-draft-preview[\s\S]*?faceHtml\(st, card, side\)/,
    "draft preview must reuse the saved-card markdown/ruby sanitizer");
  assert.match(helper, /<textarea class="fc-ed"[\s\S]*?esc\(raw\)/,
    "the original source must remain escaped and editable, never injected as HTML");

  const rendererStart = FLASHCARD.indexOf("function cardHtml(st, c, i)");
  const rendererEnd = FLASHCARD.indexOf("function bindSlide", rendererStart);
  const renderer = FLASHCARD.slice(rendererStart, rendererEnd);
  assert.match(renderer, /c\._st === 'draft'[\s\S]*?draftFieldHtml\(st, c, '正面', 'front', 'front'\)/);
  assert.match(renderer, /draftFieldHtml\(st, c, '背面', 'back', 'back'\)/);
  assert.match(renderer, /fc-del[\s\S]*?fc-add/,
    "rich preview must not remove draft delete/save actions");

  const editBinding = FLASHCARD.slice(
    FLASHCARD.indexOf("slide.querySelectorAll('.fc-ed')"),
    FLASHCARD.indexOf("slide.querySelectorAll('.fc-e')"),
  );
  assert.match(editBinding, /preview\.innerHTML = faceHtml\(st, st\.cards\[i\], side\)/,
    "live preview must be regenerated by the safe face renderer");
  assert.doesNotMatch(editBinding, /preview\.innerHTML\s*=\s*ta\.value/,
    "raw textarea input must never be assigned directly to innerHTML");
});

test("review workspace has one bounded face scroller and a fixed bottom improvement dock", () => {
  // 高度改由用户拖动手柄决定（--rv-h）。workspace 不能再用祖先的固定 80%
  // 限制，否则长对话的 min-content 会把滑块卡死在半屏；实际边界由
  // _reviewHeightBounds 按侧栏当前可用高度计算。
  assert.match(
    REVIEW,
    /#asst-review-workspace\{[^}]*flex:0 0 var\(--rv-h,min\(54vh,520px\)\)[^}]*height:var\(--rv-h,min\(54vh,520px\)\)[^}]*max-height:none[^}]*overflow:hidden/,
  );
  assert.match(
    REVIEW,
    /function _reviewHeightBounds\(\)[\s\S]*?paneHeight - reserved - minThread/,
    "slider bounds must come from the live pane, not chat message width or min-content",
  );
  assert.match(REVIEW, /touch-action:none/, "拖动手柄必须自己吃掉纵向手势，否则 iOS 当页面滚动");
  assert.match(
    REVIEW,
    /#rc-review-body\{[^}]*height:100%[^}]*overflow:hidden/,
  );
  assert.match(
    REVIEW,
    /#asst-review-workspace\.rv-card-collapsed,#asst-review-workspace\.rv-card-empty\{[^}]*height:auto/,
    "collapsing the card must not reserve an empty fixed-height workspace",
  );
  assert.match(
    REVIEW,
    /\.rv-card-panel\{[^}]*display:flex[^}]*min-height:0[^}]*overflow:hidden/,
  );
  assert.match(
    REVIEW,
    /\.rv-review-card \.vc-card-bd\.rv-review-layout\{[^}]*display:flex[^}]*overflow:hidden!important/,
  );
  assert.match(
    REVIEW,
    /\.rv-review-controls\{[^}]*flex:0 1 45%[^}]*max-height:45%[^}]*overflow:hidden/,
  );
  assert.match(
    REVIEW,
    /\.rv-review-controls>\.rv-improve-toggle\{[^}]*flex:0 0 auto[^}]*width:100%/,
  );
  // 改进面板是卡片内部的底部 sheet：不改变卡片布局，也保留上半张卡作对照。
  assert.match(
    REVIEW,
    /\.rv-improve-panel\{[^}]*position:absolute[^}]*overflow-y:auto/,
  );
  assert.match(
    REVIEW,
    /\.rv-improve-panel\{[^}]*left:0;right:0;bottom:0[^}]*max-height:min\(62%,420px\)/,
    "bottom sheet must leave part of the card visible instead of covering it all",
  );
  assert.match(
    REVIEW,
    /rendered\.bd\.classList\.add\('rv-review-layout'\)/,
  );
  assert.match(
    REVIEW,
    /panel\.classList\.toggle\('rv-improve-open', _improveExpanded\)/,
  );
  const pagerMount = REVIEW.indexOf(
    "if (RC.flashcard && typeof RC.flashcard.bindPager === 'function')",
  );
  const dockMount = REVIEW.indexOf(
    "reviewControls.className = 'rv-review-controls'",
    pagerMount,
  );
  assert.ok(
    dockMount > pagerMount,
    "the improvement dock must be mounted after the card pager at the bottom",
  );
  // 「改进」按钮挪到了头部那一行（跟 ⟳ / 收起展开并列）——用户要求：
  // 它原来独占卡片面板底部一整行，而那一行本来就是放开关的地方。
  // 面板本身仍挂在 reviewControls 里（它现在是浮层，位置由 CSS 定，不占布局）。
  assert.match(
    REVIEW.slice(dockMount, REVIEW.indexOf("function _selectCard", dockMount)),
    /toolbar\.appendChild\(improveToggle\)[\s\S]*?_appendImprovePanel\(reviewControls, card\)[\s\S]*?panel\.appendChild\(reviewControls\)/,
    "the toggle stays in the toolbar outside the overlay so it can always close it",
  );
});
