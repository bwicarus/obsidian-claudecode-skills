#!/usr/bin/env python3
"""build_jp_expressions.py — 从本地 JMdict 分片生成「多词表达」表,供预处理分词把 unidic 短単位并成词典词。

用户 2026-09-07 实锤:なんだか / もしかしたら / かしら / かもしれない 在阅读器里被分词从中间打断
(unidic 短単位:なん|だ|か、もし|か|し|たら、か|も|しれ|ない)。这些都是 JMdict 里的整条(exp/adv/prt/conj/aux),
按词性规则拼不出来,只能靠词典:分词后对相邻词元做最长匹配,拼起来在这张表里就并成一词
(reader_book_ocr_worker._merge_short_units 的词典段;守卫见那边:跨度里不能有普通名词/记号)。

只收功能词类(exp/adv/adv-to/conj/prt/aux/aux-v/aux-adj/int/pn)的 forms + readings,长度 2..12,
一行一条,写到 _server_deploy/data/jp_expressions.txt(UTF-8,LF)。分片默认在 ios/BWReader/DictionaryData/shards
(由 ios/BWReader/build_jmdict_dictionary.py 产出,不入库);没有分片时用 --shards 指路径。
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DEFAULT_SHARDS = ROOT / "ios" / "BWReader" / "DictionaryData" / "shards"
DEFAULT_OUTPUT = ROOT / "_server_deploy" / "data" / "jp_expressions.txt"
# 只收"拼不出来、只能靠词典"的功能词类;名词/动词/形容词整条不收(那些由词性规则处理,收了会把 上に/ことに 这类误并)
ALLOWED_POS = {"exp", "adv", "adv-to", "conj", "prt", "aux", "aux-v", "aux-adj", "int", "pn"}
MIN_LEN, MAX_LEN = 2, 12


def collect(shards_dir: Path) -> tuple[set[str], int]:
    terms: set[str] = set()
    entries = 0
    for path in sorted(glob.glob(os.path.join(str(shards_dir), "*.json"))):
        with open(path, encoding="utf-8") as fh:
            shard = json.load(fh)
        for entry in shard.get("entries", []):
            pos = set(str(p) for p in (entry.get("pos") or []))
            if not pos or not pos.issubset(ALLOWED_POS):
                continue
            entries += 1
            for term in list(entry.get("forms") or []) + list(entry.get("readings") or []):
                term = str(term or "").strip()
                if MIN_LEN <= len(term) <= MAX_LEN and " " not in term and "　" not in term:
                    terms.add(term)
    return terms, entries


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--shards", type=Path, default=DEFAULT_SHARDS)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args(argv)
    if not args.shards.is_dir():
        print(f"分片目录不存在: {args.shards}(先跑 ios/BWReader/build_jmdict_dictionary.py)", file=sys.stderr)
        return 2
    terms, entries = collect(args.shards)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# generated by scripts/vocab/build_jp_expressions.py from JMdict (CC BY-SA 4.0, EDRDG); one expression per line\n")
        for term in sorted(terms):
            fh.write(term + "\n")
    print(f"{entries} 条功能词类条目 → {len(terms)} 个表达 → {args.output} ({args.output.stat().st_size} bytes)")
    for probe in ("なんだか", "もしかしたら", "かもしれない", "かもしれません", "における", "には", "として", "ことに", "ように"):
        print(f"  {probe}: {'有' if probe in terms else '无'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
